// Generate a TypeScript module that exports the profile PNG as a base64 string.
// Run before dev/build to regenerate. Output: src/utils/profileDataUrl.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const PNG_PATH = path.join(root, "src/assets/images/brand/profile.png");
const OUT_PATH = path.join(root, "src/utils/profileDataUrl.ts");

const buf = readFileSync(PNG_PATH);
const b64 = buf.toString("base64");
const content = `// AUTO-GENERATED by scripts/build-profile-data-url.mjs. Do not edit by hand.
// Used by og-template.ts as an inline data URL for the satori <img> source.
export const PROFILE_DATA_URL =
  "data:image/png;base64,${b64}";
`;

mkdirSync(path.dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, content, "utf-8");
console.log(`Wrote ${OUT_PATH} (${(buf.length / 1024).toFixed(1)} KB raw, ${(b64.length / 1024).toFixed(1)} KB base64)`);
