type FontSpec = {
  name: string;
  data: ArrayBuffer;
  weight: number;
  style: "normal" | "italic";
};

function hashString(str: string): number {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) >>> 0;
  }
  return h;
}

const VARIANTS: OgVariant[] = [
  "split",
  "centered",
  "gradient",
  "minimal",
  "banner",
  "mirror",
  "stack",
  "corner",
  "cover",
];

/** Deterministic design selection seeded by the post/site title. */
export function pickDesign(
  title: string,
  variant?: OgVariant,
  palette?: 0 | 1 | 2 | 3 | 4 | 5
): Design {
  const h = hashString(title);
  return {
    variant: variant ?? VARIANTS[h % VARIANTS.length],
    palette: PALETTES[palette ?? ((h >> 3) % PALETTES.length)],
  };
}

async function loadFonts(siteUrl: URL): Promise<FontSpec[]> {
  const fonts = fontData["--font-google-sans-code"];
  const regularPath = getFontPathByWeight(fonts, 400);
  const boldPath = getFontPathByWeight(fonts, 700);
  if (!regularPath || !boldPath) {
    throw new Error("Cannot find Google Sans Code font paths.");
  }

  const [regular, bold] = await Promise.all([
    fetch(experimental_getFontFileURL(regularPath, siteUrl)).then(r =>
      r.arrayBuffer()
    ),
    fetch(experimental_getFontFileURL(boldPath, siteUrl)).then(r =>
      r.arrayBuffer()
    ),
  ]);

  return [
    { name: "Google Sans Code", data: regular, weight: 400, style: "normal" },
    { name: "Google Sans Code", data: bold, weight: 700, style: "normal" },
  ];
}

function hexToRgba(hex: string, alpha: number): string {
  const h = hex.replace("#", "");
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

// Short connector words kept lowercase in Title Case (except when first).
const TITLE_CASE_MINOR = new Set([
  "a",
  "an",
  "and",
  "at",
  "by",
  "for",
  "in",
  "of",
  "on",
  "or",
  "the",
  "to",
  "with",
]);

function toTitleCase(str: string): string {
  return str
    .split(/\s+/)
    .map((word, i, arr) => {
      const trimmed = word.replace(/[.!?]$/, "");
      const punct = word.slice(trimmed.length);
      const lower = trimmed.toLowerCase();
      const isFirst = i === 0;
      const isLast = i === arr.length - 1;
      if (
        !isFirst &&
        !isLast &&
        TITLE_CASE_MINOR.has(lower) &&
        !/[A-Z]/.test(trimmed.slice(1))
      ) {
        return trimmed + punct;
      }
      return trimmed.charAt(0).toUpperCase() + trimmed.slice(1) + punct;
    })
    .join(" ");
}

