// Shared OG image renderer with design variations.
//
// Produces 1200x630 social cards matching kanadakurniawan.com branding:
//   - dark gradient background tinted by the active palette
//   - inset rounded frame with corner accents
//   - two soft ambient gradient orbs
//   - circular profile photo with gradient ring (embedded via loadAdditionalAsset)
//   - the domain always rendered as a gradient-filled pill ("special background")
//   - optional meta chip (e.g. a tag) and subtitle
//   - deterministic layout + accent-palette variation per seed (post title)
//
// Layouts (9) — photo/text positions vary so templates can be rotated:
//   - "split"    : photo right-middle, text left
//   - "mirror"   : photo left-middle, text right-aligned
//   - "centered" : photo bottom-center, text center
//   - "gradient" : photo top-right small, text bottom-left (magazine)
//   - "minimal"  : photo top-right small, big title bottom-left (sparse)
//   - "banner"   : photo top-right small, text over horizontal gradient band
//   - "stack"    : photo top-center, text centered lower third
//   - "corner"   : photo bottom-right overlapping footer, text top-left
//   - "cover"    : large photo right bleeding off-canvas, text on soft panel
//
// Palettes (6): teal/blue, amber/pink, indigo/purple, emerald/cyan,
//               rose/orange, sky/violet. Each tints the background gradient.
//
// Branding rule: the author name appears only as "by <author>" (footerLeft),
// and the domain only as "kanadakurniawan.com" — always inside a gradient pill.
//
// Used by /og.jpg (site default), /og/[name].jpg and /og/[name].webp (per post).
// Output: JPEG q80 (mozjpeg) or WebP q85 — small and sharp.
